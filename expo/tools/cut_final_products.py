# НАТЮРМОРТ ФИНАЛА — ЦЕЛИКОМ, БЕЗ ХИРУРГИИ (Эльдар, 05.11.2026: «не убирай
# стол, а сделай этот стол частью стола, поверхности. Не надо ничего вырезать,
# просто сделай это целиком и полностью изображением на столе — так же, как у
# тебя сделан стол на 1970 году»).
#
# Прежний ассет был обрезан сверху (оставляли только верхнюю плоскость стойки
# рендера, лицевую грань отрезали) и ещё растушёвывали дальнюю кромку белой
# подложки. Эльдар поправил сам кадр: теперь в нём своя столешница, доходящая до
# нижней кромки файла, и фон над приборами прозрачен. Значит резать нечего —
# берём как есть, только обрезаем пустые поля по альфе.
#
# Замерено на файле: 1672 × 941, рамка по альфе x 0…1671, y 84…940; фон над
# приборами лежит с альфой 0 (серый виден только если подложить его под что-то).
from PIL import Image
import numpy as np
import os

SRC = 'src/pictures/Expo timeline artefacts/final products.png'
DST = 'assets/photo'

im = Image.open(SRC).convert('RGBA')
al = np.array(im)[:, :, 3]
xs = np.where((al > 110).sum(0) > 3)[0]
ys = np.where((al > 110).sum(1) > 3)[0]
box = (int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1)
out = im.crop(box)
out.save(os.path.join(DST, 'final_products.png'))
out.save(os.path.join(DST, 'final_products.webp'), quality=94, method=6)
print('final_products  %d x %d  из окна %s' % (out.width, out.height, box))
