# ДВА СОСТОЯНИЯ ОДНОЙ КОРОНКИ ДЛЯ РЕКРЕАЦИИ 2009-го (Эльдар, 04.11.2026).
#
# В артефактах лежит один файл с ДВУМЯ коронками в кадре: слева — погашенная
# (слоёная половина мертва, монолит просто белый), справа — та же самая, но
# монолит горит изнутри. Эльдар сгенерировал их одним кадром специально, чтобы
# геометрия совпала: зал держит оба состояния слоями и проявляет верхний сквозь
# бегущую маску — так свет проходит по срезу слева направо.
#
# ЗАМЕРЕНО НА ФАЙЛЕ (не на глаз):
#   предметы занимают колонки 5…639 и 647…1281 — оба шириной ровно 635;
#   при сдвиге правого на +2 пикселя силуэты расходятся на 1814 точек из
#   329 250 (0,55 %), и то по мягкому нижнему краю;
#   внутри силуэта левая половина предмета в двух состояниях отличается на 8
#   единиц цвета, правая — на 30. Это и есть раскол «погашено / горит».
# Поэтому: режем пополам, правую половину двигаем на +2, и обрезаем ОБА кадра
# ОДНОЙ рамкой — иначе слои разъедутся и проявка маской даст двоение.
from PIL import Image
import numpy as np
import os

SRC = 'src/pictures/Expo timeline artefacts/Comparative Molar Crown Cross-Sections.png'
DST = 'assets/photo'
SPLIT, DX = 644, 2          # середина кадра и замеренный сдвиг правого предмета

a = np.array(Image.open(SRC).convert('RGBA'))
dead = a[:, :SPLIT].copy()
live = np.roll(a[:, SPLIT:], DX, axis=1).copy()

# одна рамка на оба: объединение силуэтов
al = np.maximum(dead[:, :, 3], live[:, :, 3])
xs = np.where((al > 100).any(0))[0]
ys = np.where((al > 100).any(1))[0]
x0, x1, y0, y1 = int(xs.min()), int(xs.max()) + 1, int(ys.min()), int(ys.max()) + 1

for name, arr in (('r_bz_crown_dead', dead), ('r_bz_crown_live', live)):
    out = Image.fromarray(arr[y0:y1, x0:x1])
    out.save(os.path.join(DST, name + '.png'))
    out.save(os.path.join(DST, name + '.webp'), quality=94, method=6)
    print('%s  %d x %d' % (name, out.width, out.height))
print('общая рамка', (x0, y0, x1, y1))
